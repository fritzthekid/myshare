#!/usr/bin/env bash
# Installs the myshare CUPS backend + sets up the printer queues. Must run
# as root (sudo). Idempotent - can be safely run again (e.g. after a
# "go build" with a new backend version).
#
# Usage:
#   sudo ./deploy/install.sh [path-to-backend-binary]
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BACKEND_BIN="${1:-$REPO_ROOT/backend}"

INSTALL_BIN=/usr/local/lib/myshare/backend
ENV_FILE=/etc/myshare/backend.env
PPD_FILE=/etc/myshare/cloudpdf.ppd
BACKEND_LINK=/usr/lib/cups/backend/nextcloud

if [ "$(id -u)" -ne 0 ]; then
  echo "Please run with sudo: sudo $0" >&2
  exit 1
fi

if [ ! -x "$BACKEND_BIN" ]; then
  echo "Backend binary not found or not executable: $BACKEND_BIN" >&2
  echo "Build it first as a regular user: go build -o backend ./cmd/backend" >&2
  exit 1
fi

install -d -m 755 /usr/local/lib/myshare
install -m 755 "$BACKEND_BIN" "$INSTALL_BIN"

install -d -m 755 /var/lib/myshare/tmp

install -d -m 755 /etc/myshare
if [ ! -f "$ENV_FILE" ]; then
  install -m 600 "$REPO_ROOT/deploy/backend.env.example" "$ENV_FILE"
  echo "Env file created: $ENV_FILE"
  echo "  -> still need to fill in NC_BASE_URL / NC_USERNAME / NC_PASSWORD!"
fi
chmod 600 "$ENV_FILE"
chown root:root "$ENV_FILE"

install -m 644 "$REPO_ROOT/deploy/cloudpdf.ppd" "$PPD_FILE"

if [ -f "$REPO_ROOT/raspi/scripts/toraspi.sh" ]; then
  install -m 755 "$REPO_ROOT/raspi/scripts/toraspi.sh" /usr/local/lib/myshare/toraspi.sh
  echo "Output hook installed: /usr/local/lib/myshare/toraspi.sh"
  echo "  -> used automatically by the \"CloudToRaspi\" queue"
  echo "     (see deploy/nextcloud-backend-wrapper.sh); for sendfile/webshare"
  echo "     set MYSHARE_DISPLAY_HOOK in $ENV_FILE instead"
fi

if [ -f "$REPO_ROOT/scripts/push-to-cloudweb.sh" ]; then
  install -m 755 "$REPO_ROOT/scripts/push-to-cloudweb.sh" /usr/local/lib/myshare/push-to-cloudweb.sh
  echo "Output hook installed: /usr/local/lib/myshare/push-to-cloudweb.sh"
  echo "  -> used automatically by the \"CloudWeb\" queue"
  echo "     (see deploy/nextcloud-backend-wrapper.sh); for sendfile/webshare"
  echo "     set MYSHARE_DISPLAY_HOOK in $ENV_FILE instead"
fi

install -m 700 "$REPO_ROOT/deploy/nextcloud-backend-wrapper.sh" "$BACKEND_LINK"
chown root:root "$BACKEND_LINK"

if [ -x "$REPO_ROOT/webshare" ]; then
  install -m 755 "$REPO_ROOT/webshare" /usr/local/lib/myshare/webshare

  if ! grep -q '^WEBSHARE_TOKEN=.\+' "$ENV_FILE" 2>/dev/null; then
    TOKEN=$(openssl rand -hex 24)
    sed -i '/^#WEBSHARE_TOKEN=/d' "$ENV_FILE"
    printf '\n# generated by install.sh (%s)\nWEBSHARE_TOKEN=%s\n' "$(date -Iseconds)" "$TOKEN" >> "$ENV_FILE"
    echo "WEBSHARE_TOKEN generated and added to $ENV_FILE."
  fi

  install -m 644 "$REPO_ROOT/deploy/webshare.service" /etc/systemd/system/myshare-webshare.service
  systemctl daemon-reload
  systemctl enable --now myshare-webshare
  systemctl restart myshare-webshare
  WEBSHARE_INSTALLED=1
fi

if [ -x "$REPO_ROOT/cloudweb" ]; then
  install -m 755 "$REPO_ROOT/cloudweb" /usr/local/lib/myshare/cloudweb
  install -m 644 "$REPO_ROOT/deploy/cloudweb.service" /etc/systemd/system/myshare-cloudweb.service
  systemctl daemon-reload
  systemctl enable --now myshare-cloudweb
  systemctl restart myshare-cloudweb
  CLOUDWEB_INSTALLED=1
fi

systemctl restart cups

# Remove the old default queue from earlier install.sh runs - replaced by
# two queues each permanently routed to their own display target (see
# deploy/nextcloud-backend-wrapper.sh, which routes based on the $PRINTER
# set by CUPS).
if lpstat -p CloudPDF >/dev/null 2>&1; then
  lpadmin -x CloudPDF
  echo "Removed old \"CloudPDF\" queue (replaced by CloudToRaspi/CloudWeb)."
fi

for QUEUE in CloudToRaspi CloudWeb; do
  lpadmin -p "$QUEUE" -E -v nextcloud:/ -P "$PPD_FILE" -o printer-is-shared=false
  cupsenable "$QUEUE"
  cupsaccept "$QUEUE"
done

cat <<EOF

Done. Queues "CloudToRaspi" (-> Pi display) and "CloudWeb" (-> cloudweb
display) both point to $BACKEND_LINK; which hook runs is decided solely by
the chosen queue name.

If not done yet: fill in credentials in $ENV_FILE

Test print:
  lp -d CloudToRaspi $REPO_ROOT/test-print.pdf
  lp -d CloudWeb $REPO_ROOT/test-print.pdf
  tail -f /var/log/cups/error_log        # on problems
  tail -f /var/lib/myshare/tmp/links.log
EOF

if [ "${WEBSHARE_INSTALLED:-0}" = "1" ]; then
  TOKEN=$(grep '^WEBSHARE_TOKEN=' "$ENV_FILE" | tail -1 | cut -d= -f2-)
  LISTEN=$(grep '^WEBSHARE_LISTEN=' "$ENV_FILE" | tail -1 | cut -d= -f2-)
  cat <<EOF

webshare is running (systemctl status myshare-webshare).
URL (adjust the port if WEBSHARE_LISTEN != default ":8642"):
  http://<this-machine's-IP-or-hostname>${LISTEN:-:8642}/s/$TOKEN/
EOF
fi

if [ "${CLOUDWEB_INSTALLED:-0}" = "1" ]; then
  cat <<EOF

cloudweb is running (systemctl status myshare-cloudweb).
Display page: http://<this-machine's-IP-or-hostname>:40080/
To enable as the display hook, set MYSHARE_DISPLAY_HOOK in $ENV_FILE:
  MYSHARE_DISPLAY_HOOK=/usr/local/lib/myshare/push-to-cloudweb.sh
EOF
fi
